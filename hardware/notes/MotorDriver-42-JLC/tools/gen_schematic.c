static void svg_partition(FILE *f, int x, int y, int w, int h, const char *title, const char *sub) {
    fprintf(f,
        "<rect x=\"%d\" y=\"%d\" width=\"%d\" height=\"%d\" class=\"box\"/>\n"
        "<rect x=\"%d\" y=\"%d\" width=\"180\" height=\"18\" fill=\"white\"/>\n"
        "<text x=\"%d\" y=\"%d\" class=\"bt\">%s</text>\n"
        "<text x=\"%d\" y=\"%d\" class=\"bs\">%s</text>\n",
        x, y, w, h,
        x+8, y, x+14, y+13, title,
        x+190, y+13, sub
    );
}

static void svg_component(FILE *f, int x, int y, int w, int h, const char *ref, const char *foot, const char *param) {
    fprintf(f,
        "<rect x=\"%d\" y=\"%d\" width=\"%d\" height=\"%d\" class=\"comp\"/>\n"
        "<text x=\"%d\" y=\"%d\" class=\"ct\">%s</text>\n"
        "<text x=\"%d\" y=\"%d\" class=\"cs\">%s</text>\n"
        "<text x=\"%d\" y=\"%d\" class=\"cs\">%s</text>\n",
        x, y, w, h,
        x + w/2, y+16, ref,
        x + w/2, y+28, foot,
        x + w/2, y+40, param
    );
}

